#include "LTHLSubtarget.h"
#include "LTHL.h"

using namespace llvm;

#define DEBUG_TYPE "lthl-subtarget"

#define GET_SUBTARGETINFO_TARGET_DESC
#define GET_SUBTARGETINFO_CTOR
#include "LTHLGenSubtargetInfo.inc"

LTHLSubtarget::LTHLSubtarget(const Triple &TT, StringRef CPU,
                              StringRef TuneCPU, StringRef FS,
                              const TargetMachine &TM)
    : LTHLGenSubtargetInfo(TT, CPU, TuneCPU, FS), RegInfo() {
  initializeSubtargetDependencies(CPU, TuneCPU, FS);
  InstrInfo = std::make_unique<LTHLInstrInfo>(*this);
  FrameLoweringInfo = std::make_unique<LTHLFrameLowering>(*this);
  TLInfo = std::make_unique<LTHLTargetLowering>(TM, *this);
  TSInfo = std::make_unique<LTHLSelectionDAGInfo>();
}

LTHLSubtarget &
LTHLSubtarget::initializeSubtargetDependencies(StringRef CPU,
                                                StringRef TuneCPU,
                                                StringRef FS) {
  // ParseSubtargetFeatures is generated by GET_SUBTARGETINFO_CTOR above;
  // it walks the FS (-mattr=) string and sets HasInt, etc. per the
  // SubtargetFeature defs in LTHL.td.
  ParseSubtargetFeatures(CPU, TuneCPU, FS);
  return *this;
}
